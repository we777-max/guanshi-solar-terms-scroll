export function skylineHeight(index,x) {
  const points=SKYLINES[index];
  const right=Math.max(1,points.findIndex(point=>point[0]>=x));
  const a=points[right-1],b=points[right];
  return a[1]+(b[1]-a[1])*(x-a[0])/(b[0]-a[0]);
}
function inPolygon(points,x,y) {
  let inside=false;
  for(let i=0,j=points.length-1;i<points.length;j=i++) {
    const a=points[i],b=points[j];
    if((a[1]>y)!==(b[1]>y)&&x<(b[0]-a[0])*(y-a[1])/(b[1]-a[1])+a[0])inside=!inside;
  }
  return inside;
}
function nearPolygon(points,x,y) {
  return points.some((a,i)=>{
    const b=points[(i+1)%points.length],dx=b[0]-a[0],dy=b[1]-a[1];
    const t=Math.max(0,Math.min(1,((x-a[0])*dx+(y-a[1])*dy)/(dx*dx+dy*dy||1)));
    return Math.hypot(x-a[0]-t*dx,y-a[1]-t*dy)<=8;
  });
}
export function skyContains(index,x,y) {
  return x>=0&&x<=2172&&y>=0&&y<skylineHeight(index,x)&&!TREE_SKY_CUTOUTS[index].some(points=>inPolygon(points,x,y)||nearPolygon(points,x,y));
}
export function moonDiskPath(phase) {
  const angle=((phase%360)+360)%360, side=angle<=180?1:-1, terminator=Math.cos(angle*Math.PI/180);
  const points=[];
  for(let i=0;i<=64;i++){const y=-1+2*i/64;points.push([side*Math.sqrt(Math.max(0,1-y*y)),y]);}
  for(let i=64;i>=0;i--){const y=-1+2*i/64;points.push([side*terminator*Math.sqrt(Math.max(0,1-y*y)),y]);}
  return `M${points.map(point=>point.map(n=>n.toFixed(5)).join(' ')).join('L')}Z`;
}
export function getMoonAppearance(date) {
  const instant=new Date(date);
  if(!Number.isFinite(instant.getTime()))throw new TypeError('无效观月日期');
  const distanceKm=Astronomy.GeoMoon(instant).Length()*Astronomy.KM_PER_AU;
  const phase=Astronomy.MoonPhase(instant), illumination=Astronomy.Illumination(Astronomy.Body.Moon,instant).phase_fraction;
  const labels=['朔','娥眉月','上弦月','盈凸月','望','亏凸月','下弦月','残月'];
  return {date:instant,phase,illumination,distanceKm,scale:384400/distanceKm,
    angularDiameter:2*Math.asin(1737.4/distanceKm)*180/Math.PI*60,
    label:labels[Math.floor((phase+22.5)%360/45)],path:moonDiskPath(phase)};
}
